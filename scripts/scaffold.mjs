#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { validateSpec } from './validate-spec.mjs';
import { checkAssembly, formatReport } from './check-assembly.mjs';
import { bundleProject } from './bundle.mjs';

const here = path.dirname(fileURLToPath(import.meta.url));
const bundle = path.resolve(here, '..');

const usage = 'Usage: node scripts/scaffold.mjs <scene.json> <output-directory>';
const specArg = process.argv[2];
const outArg = process.argv[3];
if (!specArg || !outArg) {
  console.error(usage);
  process.exit(2);
}

const specPath = path.resolve(specArg);
const outDir = path.resolve(outArg);
let spec;
try {
  spec = JSON.parse(fs.readFileSync(specPath, 'utf8'));
} catch (error) {
  console.error(`FAIL  cannot read spec: ${error.message}`);
  process.exit(1);
}
const result = validateSpec(spec, path.basename(specPath));
if (result.errors.length) {
  console.error(`FAIL  ${specPath}`);
  for (const error of result.errors) console.error(`  - ${error}`);
  process.exit(1);
}
const assembly = checkAssembly(spec);
if (!assembly.passed) {
  console.error(formatReport(assembly));
  console.error('FAIL  assembly review gate: fix collisions or declare reviewed structural mates before scaffolding.');
  process.exit(1);
}

if (fs.existsSync(outDir) && fs.readdirSync(outDir).length) {
  console.error(`FAIL  output directory is not empty: ${outDir}`);
  console.error('      choose a new directory; scaffold never deletes user files.');
  process.exit(1);
}

fs.mkdirSync(outDir, { recursive: true });
fs.cpSync(path.join(bundle, 'assets', 'template'), outDir, { recursive: true });
fs.cpSync(path.join(bundle, 'assets', 'vendor'), path.join(outDir, 'vendor'), { recursive: true });
fs.copyFileSync(path.join(here, 'check-assembly.mjs'), path.join(outDir, 'check-assembly.mjs'));
fs.writeFileSync(path.join(outDir, 'scene.json'), JSON.stringify(spec, null, 2) + '\n', 'utf8');
fs.writeFileSync(
  path.join(outDir, 'scene-spec.js'),
  `/* Generated by exploded-view-studio scaffold.mjs from ${path.basename(specPath)}. */\nwindow.SCENE_SPEC = ${JSON.stringify(spec, null, 2)};\n`,
  'utf8'
);
fs.writeFileSync(
  path.join(outDir, 'README.md'),
  `# ${spec.product?.name || 'Product'} — Exploded View Studio\n\n` +
  `Generated from \`${path.basename(specPath)}\` with ${result.modules} modules and ${result.parts} procedural parts.\n\n` +
  `**Send \`standalone.html\` to a phone**: it is a single offline file containing CSS, fonts, Three.js, the scene spec and the engine. Open it directly, no server or network required.\n\n` +
  `For development, \`index.html\` loads the readable modular files. Both builds are offline.\n\n` +
  `- \`standalone.html\` — all-in-one delivery build for mobile/desktop sharing.\n` +
  `- \`scene-spec.js\` — product, design tokens and module data.\n` +
  `- \`scene.json\` — source spec for the assembly reviewer.\n` +
  `- \`check-assembly.mjs\` — collision reviewer; run it before every visual review.\n` +
  `- \`design.js\` — eight product-adaptive art-direction presets.\n` +
  `- \`engine.js\` — spec-driven renderer and interaction layer.\n` +
  `- \`styles.css\` — tokenized workbench UI.\n` +
  `- \`fonts/\` — local subsetted Space Grotesk, Newsreader, Manrope and IBM Plex Mono.\n` +
  `- \`LICENSES/\` — OFL/ISC licenses and asset provenance for offline distribution.\n` +
  `- \`vendor/three.min.js\` — local Three.js r152.2.\n\n` +
  `Art direction: **${spec.design?.preset || 'auto (inferred from product)'}**.
Research mode: **${spec.research?.mode || 'not recorded'}**.

Assembly gate: **PASS** (${assembly.unapproved.length} unapproved intersections, ${assembly.internalModules} internal modules, review ${assembly.review.status}).

Before delivery: run \`node check-assembly.mjs scene.json\`, inspect assembled/front/side/top/exploded views, then run the static audit. Never set \`assembly.review.status = "passed"\` without that visual inspection.
Use \`node "${path.join(bundle, 'scripts', 'audit.mjs').split(path.sep).join('/')}" .\` from this folder to run the static audit.\n`,
  'utf8'
);

const bundled = bundleProject(outDir);
console.log(`OK    scaffolded ${outDir}`);
console.log(`      ${result.modules} modules · ${result.parts} parts · ${result.mass} g`);
console.log(`      assembly clean · research ${spec.research?.mode || 'not recorded'}`);
console.log(`      standalone.html  ${(bundled.bytes / 1024).toFixed(1)} KB  (share this file)`);